-- Atomic Transactional Order Placement Function
-- SECURITY NOTE: the sale price is never trusted from the client. It is always
-- read from the locked inventory row; a caller-supplied price is only honored
-- when the caller is an admin (Key Business Rule: "price per cube editable by
-- admin only"). This closes the gap where a non-admin (or a direct RPC call)
-- could previously submit an arbitrary price_per_cube and have it accepted.
--
-- CASH-TO-OLD-DEBT OFFSET (debtsLogic.md rules):
--   CASH order: the cash amount (= new order total) is applied FIFO against
--   any pre-existing outstanding debts for this customer. Each old debt is
--   reduced/settled in order. If an old debt is only partially cleared, its
--   created_at is refreshed to today so its aging clock resets. The new sale
--   itself is always recorded as payment_type='cash' — no new debt is created
--   for this sale regardless of whether any old debt still remains.
--
--   DEBT CREDIT order: unaffected — a new debt record is created for this
--   sale exactly as before; old debts are not touched.
--
-- Example: customer owes 50,000 (old debt). Places a new 20,000 cash order.
-- The 20,000 cash is applied to the old debt -> old debt drops to 30,000 and
-- its date is refreshed to today. New sale is recorded as cash (fully paid
-- from this transaction's perspective). Total outstanding remains 30,000.
create or replace function public.place_order_transaction(
  p_customer_id bigint,
  p_cube_type text,
  p_quantity integer,
  p_price_per_cube numeric,
  p_payment_type text,
  p_created_by text
) returns jsonb as $$
declare
  v_item_id bigint;
  v_current_qty integer;
  v_inventory_price numeric(10, 2);
  v_final_price numeric(10, 2);
  v_new_qty integer;
  v_sale_code text;
  v_total_amount numeric(10, 2);
  v_sale_id bigint;
  v_debt_id bigint := null;
  v_now timestamp with time zone := timezone('utc'::text, now());
  v_cash_remaining numeric(10, 2);
  v_applied_to_old_debt numeric(10, 2) := 0;
  v_old_debt record;
  v_apply_amt numeric(10, 2);
  v_old_new_remaining numeric(10, 2);
  v_old_new_status text;
begin
  -- Validate inputs
  if p_customer_id is null then raise exception 'Customer is required'; end if;
  if p_quantity <= 0 then raise exception 'Quantity must be a positive integer'; end if;
  if p_payment_type not in ('cash', 'debt') then raise exception 'Invalid payment type'; end if;

  -- 1. Lock inventory row and read the authoritative price + stock
  select id, quantity, price_per_cube into v_item_id, v_current_qty, v_inventory_price
  from public.inventory
  where type = p_cube_type
  for update;

  if not found then raise exception 'Inventory item for % not found', p_cube_type; end if;
  if v_current_qty < p_quantity then raise exception 'Insufficient stock. Available: %', v_current_qty; end if;
  if v_inventory_price is null or v_inventory_price <= 0 then
    raise exception 'Price per cube must be set before placing a sale';
  end if;

  -- Non-admins (and any caller not supplying a price) always sell at the
  -- current inventory price. Admins may override with a caller-supplied
  -- positive price (e.g. a negotiated discount).
  if public.is_admin() and p_price_per_cube is not null and p_price_per_cube > 0 then
    v_final_price := p_price_per_cube;
  else
    v_final_price := v_inventory_price;
  end if;

  v_new_qty := v_current_qty - p_quantity;

  -- 2. Deduct inventory stock
  update public.inventory
  set quantity = v_new_qty,
      updated_at = v_now
  where id = v_item_id;

  -- 3. Atomic sale code generation
  v_sale_code := public.get_next_code('sale', 'S');
  v_total_amount := v_final_price * p_quantity;

  -- 4. Cash-to-old-debt FIFO offset (cash orders only)
  -- The new order's cash is applied against old outstanding debts oldest-first.
  -- Any old debt that is only partially cleared has its created_at reset to
  -- today so its aging clock restarts. The new sale itself always stays 'cash'.
  if p_payment_type = 'cash' then
    v_cash_remaining := v_total_amount;

    for v_old_debt in
      select id, remaining_amount
      from public.debts
      where customer_id = p_customer_id
        and status in ('pending', 'partial')
      order by created_at asc
      for update
    loop
      exit when v_cash_remaining <= 0;

      v_apply_amt := least(v_cash_remaining, v_old_debt.remaining_amount);
      v_old_new_remaining := v_old_debt.remaining_amount - v_apply_amt;
      v_old_new_status := case when v_old_new_remaining <= 0 then 'settled' else 'partial' end;

      -- Update the old debt; if it still has a remaining balance, refresh its
      -- created_at to today so the aging clock resets on the outstanding amount.
      update public.debts
      set paid_amount     = paid_amount + v_apply_amt,
          remaining_amount = v_old_new_remaining,
          status          = v_old_new_status,
          created_at      = case when v_old_new_remaining > 0 then v_now else created_at end
      where id = v_old_debt.id;

      insert into public.debt_settlements (debt_id, customer_id, amount_paid, settlement_date, created_by)
      values (v_old_debt.id, p_customer_id, v_apply_amt, v_now,
              p_created_by || ' (auto-applied from sale ' || v_sale_code || ')');

      v_applied_to_old_debt := v_applied_to_old_debt + v_apply_amt;
      v_cash_remaining := v_cash_remaining - v_apply_amt;
    end loop;
  end if;

  -- 5. Create sale record (payment_type is always what the operator selected)
  insert into public.sales (
    sale_code, customer_id, cube_type, quantity, price_per_cube, total_amount, payment_type, sale_date, created_by
  ) values (
    v_sale_code, p_customer_id, p_cube_type, p_quantity, v_final_price, v_total_amount, p_payment_type, v_now, p_created_by
  ) returning id into v_sale_id;

  -- 6. Record inventory audit log
  insert into public.inventory_transactions (
    inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by
  ) values (
    v_item_id, 'sale_deduction', -p_quantity, v_current_qty, v_new_qty, v_sale_code, p_created_by
  );

  -- 7. Create a debt for this sale if it is a Debt Credit order.
  --    Cash orders never create a new debt for this sale — old debts were
  --    already reduced above; the new sale is fully settled as cash.
  if p_payment_type = 'debt' then
    insert into public.debts (
      sale_id, customer_id, total_amount, paid_amount, remaining_amount, status, created_at
    ) values (
      v_sale_id, p_customer_id, v_total_amount, 0, v_total_amount, 'pending', v_now
    ) returning id into v_debt_id;
  end if;

  return jsonb_build_object(
    'id', v_sale_id,
    'sale_code', v_sale_code,
    'customer_id', p_customer_id,
    'cube_type', p_cube_type,
    'quantity', p_quantity,
    'price_per_cube', v_final_price,
    'total_amount', v_total_amount,
    'payment_type', p_payment_type,
    'sale_date', v_now,
    'debt_id', v_debt_id,
    'applied_to_old_debt', v_applied_to_old_debt
  );
end;
$$ language plpgsql security definer;

-- Atomic Multi-Item Order Placement Transaction (SalesTab.md: a "+Add Row"
-- order with two cube types saves as ONE bill, not one sale per row).
-- Same cash-to-old-debt FIFO offset and admin-price-override rules as
-- place_order_transaction (kept in place, unused after this — harmless as
-- an additive no-op since nothing else calls it), just generalized across a
-- jsonb array of {cube_type, quantity, price_per_cube} items instead of a
-- single item. Since there are only ever two cube types, inventory rows are
-- locked in the fixed order manufactured-then-resell (rather than a generic
-- loop) to avoid deadlocking against concurrent orders/edits touching both.
create or replace function public.place_multi_item_order_transaction(
  p_customer_id bigint,
  p_items jsonb,
  p_payment_type text,
  p_created_by text
) returns jsonb as $$
declare
  v_item record;
  v_mfc_id bigint;
  v_mfc_qty integer;
  v_mfc_price numeric(10, 2);
  v_mfc_needed integer := 0;
  v_rsc_id bigint;
  v_rsc_qty integer;
  v_rsc_price numeric(10, 2);
  v_rsc_needed integer := 0;

  v_customer_mfc_price numeric(10, 2);
  v_customer_rsc_price numeric(10, 2);
  v_default_mfc_price numeric(10, 2);
  v_default_rsc_price numeric(10, 2);

  v_sale_code text;
  v_sale_id bigint;
  v_total_amount numeric(10, 2) := 0;
  v_now timestamp with time zone := timezone('utc'::text, now());
  v_resolved_price numeric(10, 2);
  v_item_subtotal numeric(10, 2);
  v_resolved_items jsonb := '[]'::jsonb;

  v_single_cube_type text;
  v_single_price numeric(10, 2);
  v_price_consistent boolean := true;

  v_debt_id bigint := null;
  v_cash_remaining numeric(10, 2);
  v_applied_to_old_debt numeric(10, 2) := 0;
  v_old_debt record;
  v_apply_amt numeric(10, 2);
  v_old_new_remaining numeric(10, 2);
  v_old_new_status text;
begin
  if p_customer_id is null then raise exception 'Customer is required'; end if;
  if p_payment_type not in ('cash', 'debt') then raise exception 'Invalid payment type'; end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then raise exception 'At least one order item is required'; end if;

  -- 1. Validate items and tally the requested quantity per cube type
  for v_item in select * from jsonb_to_recordset(p_items) as x(cube_type text, quantity integer, price_per_cube numeric) loop
    if v_item.cube_type not in ('manufactured', 'resell') then raise exception 'Invalid cube type selected'; end if;
    if v_item.quantity is null or v_item.quantity <= 0 then raise exception 'All row quantities must be positive integers'; end if;

    if v_item.cube_type = 'manufactured' then
      v_mfc_needed := v_mfc_needed + v_item.quantity;
    else
      v_rsc_needed := v_rsc_needed + v_item.quantity;
    end if;
  end loop;

  -- 2. Lock the inventory row(s) actually needed, in fixed alphabetical order
  if v_mfc_needed > 0 then
    select id, quantity, price_per_cube into v_mfc_id, v_mfc_qty, v_mfc_price
    from public.inventory where type = 'manufactured' for update;
    if not found then raise exception 'Inventory item for manufactured not found'; end if;
    if v_mfc_qty < v_mfc_needed then raise exception 'Insufficient Production stock. Available: %', v_mfc_qty; end if;
    if v_mfc_price is null or v_mfc_price <= 0 then raise exception 'Price per cube must be set before placing a sale'; end if;
  end if;

  if v_rsc_needed > 0 then
    select id, quantity, price_per_cube into v_rsc_id, v_rsc_qty, v_rsc_price
    from public.inventory where type = 'resell' for update;
    if not found then raise exception 'Inventory item for resell not found'; end if;
    if v_rsc_qty < v_rsc_needed then raise exception 'Insufficient Resell stock. Available: %', v_rsc_qty; end if;
    if v_rsc_price is null or v_rsc_price <= 0 then raise exception 'Price per cube must be set before placing a sale'; end if;
  end if;

  -- 3. Deduct the summed quantity per type
  if v_mfc_needed > 0 then
    update public.inventory set quantity = v_mfc_qty - v_mfc_needed, updated_at = v_now where id = v_mfc_id;
  end if;
  if v_rsc_needed > 0 then
    update public.inventory set quantity = v_rsc_qty - v_rsc_needed, updated_at = v_now where id = v_rsc_id;
  end if;

  -- 4. One sale_code for the whole order
  v_sale_code := public.get_next_code('sale', 'S');

  -- 4b. This customer's per-cube custom rates, if any — the non-admin
  --     default is their custom price when set, otherwise the live
  --     inventory price (customer_cube_prices is looked up server-side so
  --     it can't be spoofed by a client-supplied price_per_cube).
  select price_per_cube into v_customer_mfc_price
  from public.customer_cube_prices
  where customer_id = p_customer_id and cube_type = 'manufactured';

  select price_per_cube into v_customer_rsc_price
  from public.customer_cube_prices
  where customer_id = p_customer_id and cube_type = 'resell';

  v_default_mfc_price := coalesce(v_customer_mfc_price, v_mfc_price);
  v_default_rsc_price := coalesce(v_customer_rsc_price, v_rsc_price);

  -- 5. Resolve each item's final price (admin override honored per item;
  --    everyone else gets this customer's custom rate if set, otherwise the
  --    live inventory price for that item's cube type) and accumulate the total.
  for v_item in select * from jsonb_to_recordset(p_items) as x(cube_type text, quantity integer, price_per_cube numeric) loop
    if public.is_admin() and v_item.price_per_cube is not null and v_item.price_per_cube > 0 then
      v_resolved_price := v_item.price_per_cube;
    else
      v_resolved_price := case when v_item.cube_type = 'manufactured' then v_default_mfc_price else v_default_rsc_price end;
    end if;

    v_item_subtotal := v_resolved_price * v_item.quantity;
    v_total_amount := v_total_amount + v_item_subtotal;

    v_resolved_items := v_resolved_items || jsonb_build_object(
      'cube_type', v_item.cube_type,
      'quantity', v_item.quantity,
      'price_per_cube', v_resolved_price,
      'subtotal', v_item_subtotal
    );

    if v_single_cube_type is null then
      v_single_cube_type := v_item.cube_type;
      v_single_price := v_resolved_price;
    elsif v_single_cube_type <> v_item.cube_type or v_single_price <> v_resolved_price then
      v_price_consistent := false;
    end if;
  end loop;

  -- 6. Cash-to-old-debt FIFO offset (cash orders only) — identical logic to
  --    place_order_transaction, applied against the combined order total.
  if p_payment_type = 'cash' then
    v_cash_remaining := v_total_amount;

    for v_old_debt in
      select id, remaining_amount
      from public.debts
      where customer_id = p_customer_id
        and status in ('pending', 'partial')
      order by created_at asc
      for update
    loop
      exit when v_cash_remaining <= 0;

      v_apply_amt := least(v_cash_remaining, v_old_debt.remaining_amount);
      v_old_new_remaining := v_old_debt.remaining_amount - v_apply_amt;
      v_old_new_status := case when v_old_new_remaining <= 0 then 'settled' else 'partial' end;

      update public.debts
      set paid_amount     = paid_amount + v_apply_amt,
          remaining_amount = v_old_new_remaining,
          status          = v_old_new_status,
          created_at      = case when v_old_new_remaining > 0 then v_now else created_at end
      where id = v_old_debt.id;

      insert into public.debt_settlements (debt_id, customer_id, amount_paid, settlement_date, created_by)
      values (v_old_debt.id, p_customer_id, v_apply_amt, v_now,
              p_created_by || ' (auto-applied from sale ' || v_sale_code || ')');

      v_applied_to_old_debt := v_applied_to_old_debt + v_apply_amt;
      v_cash_remaining := v_cash_remaining - v_apply_amt;
    end loop;
  end if;

  -- 7. Insert the one sales header row. Legacy cube_type/price_per_cube are
  --    populated only when the whole order is a single (type, price) pair.
  insert into public.sales (
    sale_code, customer_id, cube_type, quantity, price_per_cube, total_amount, payment_type, sale_date, created_by
  ) values (
    v_sale_code, p_customer_id,
    case when v_price_consistent then v_single_cube_type else null end,
    v_mfc_needed + v_rsc_needed,
    case when v_price_consistent then v_single_price else null end,
    v_total_amount, p_payment_type, v_now, p_created_by
  ) returning id into v_sale_id;

  -- 8. Insert one sale_items row per input item
  for v_item in select * from jsonb_to_recordset(v_resolved_items) as y(cube_type text, quantity integer, price_per_cube numeric, subtotal numeric) loop
    insert into public.sale_items (sale_id, cube_type, quantity, price_per_cube, subtotal)
    values (v_sale_id, v_item.cube_type, v_item.quantity, v_item.price_per_cube, v_item.subtotal);
  end loop;

  -- 9. Inventory audit log, one row per type actually deducted
  if v_mfc_needed > 0 then
    insert into public.inventory_transactions (inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by)
    values (v_mfc_id, 'sale_deduction', -v_mfc_needed, v_mfc_qty, v_mfc_qty - v_mfc_needed, v_sale_code, p_created_by);
  end if;
  if v_rsc_needed > 0 then
    insert into public.inventory_transactions (inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by)
    values (v_rsc_id, 'sale_deduction', -v_rsc_needed, v_rsc_qty, v_rsc_qty - v_rsc_needed, v_sale_code, p_created_by);
  end if;

  -- 10. Create a debt for this sale if it is a Debt Credit order (unchanged
  --     pattern — one debt row keyed by sale_id/total_amount, agnostic to
  --     item count).
  if p_payment_type = 'debt' then
    insert into public.debts (
      sale_id, customer_id, total_amount, paid_amount, remaining_amount, status, created_at
    ) values (
      v_sale_id, p_customer_id, v_total_amount, 0, v_total_amount, 'pending', v_now
    ) returning id into v_debt_id;
  end if;

  return jsonb_build_object(
    'id', v_sale_id,
    'sale_code', v_sale_code,
    'customer_id', p_customer_id,
    'total_amount', v_total_amount,
    'payment_type', p_payment_type,
    'sale_date', v_now,
    'debt_id', v_debt_id,
    'applied_to_old_debt', v_applied_to_old_debt
  );
end;
$$ language plpgsql security definer;

-- Atomic Debt Settlement Transaction
-- Locks the debt row so two concurrent/duplicate settlements can never both
-- apply against the same "remaining_amount" snapshot (fixes lost-payment
-- race), and updates the debt + inserts the audit row in one transaction so
-- a failure can never leave the debt updated without a matching settlement
-- record (fixes double-apply-on-retry).
create or replace function public.settle_debt_transaction(
  p_debt_id bigint,
  p_amount_paid numeric,
  p_created_by text,
  p_payment_method text default 'cash',
  p_notes text default null
) returns jsonb as $$
declare
  v_total numeric(10, 2);
  v_paid numeric(10, 2);
  v_remaining numeric(10, 2);
  v_customer_id bigint;
  v_sale_id bigint;
  v_new_paid numeric(10, 2);
  v_new_remaining numeric(10, 2);
  v_new_status text;
  v_settlement_code text;
  v_settlement_id bigint;
  v_now timestamp with time zone := timezone('utc'::text, now());
begin
  if p_amount_paid is null or p_amount_paid <= 0 then
    raise exception 'Settlement amount must be a positive number';
  end if;

  select total_amount, paid_amount, remaining_amount, customer_id, sale_id
    into v_total, v_paid, v_remaining, v_customer_id, v_sale_id
  from public.debts
  where id = p_debt_id
  for update;

  if not found then
    raise exception 'Debt record not found';
  end if;

  if p_amount_paid > v_remaining then
    raise exception 'Payment exceeds outstanding debt. Max payable: LKR %', v_remaining;
  end if;

  v_new_paid := v_paid + p_amount_paid;
  v_new_remaining := v_total - v_new_paid;
  v_new_status := case when v_new_remaining <= 0 then 'settled' else 'partial' end;

  update public.debts
  set paid_amount = v_new_paid,
      remaining_amount = v_new_remaining,
      status = v_new_status
  where id = p_debt_id;

  v_settlement_code := public.get_next_code('settlement', 'D');

  insert into public.debt_settlements (
    debt_id, customer_id, amount_paid, payment_method, notes, settlement_date, created_by
  ) values (
    p_debt_id, v_customer_id, p_amount_paid, coalesce(p_payment_method, 'cash'), p_notes, v_now, p_created_by
  ) returning id into v_settlement_id;

  return jsonb_build_object(
    'id', v_settlement_id,
    'settlement_code', v_settlement_code,
    'debt_id', p_debt_id,
    'customer_id', v_customer_id,
    'sale_id', v_sale_id,
    'amount_paid', p_amount_paid,
    'payment_method', coalesce(p_payment_method, 'cash'),
    'notes', p_notes,
    'remaining_amount', v_new_remaining,
    'status', v_new_status,
    'settlement_date', v_now
  );
end;
$$ language plpgsql security definer;

-- Atomic Sale Edit Transaction (SalesTab.md "Edit bill button")
-- Lets an existing sale's cube type / quantity / rate / payment terms be
-- corrected after the fact, while keeping inventory and the debts ledger
-- consistent:
--   - Inventory: the sale's original quantity is restored to its original
--     cube type's stock, then the new quantity is deducted from the new
--     cube type's stock (same row if the type didn't change). Both affected
--     inventory rows are locked in a fixed (alphabetical) order so two
--     concurrent edits/orders can never deadlock against each other.
--   - Debts: cash->cash / debt->debt just re-prices the linked debt (if
--     any). debt->cash deletes the debt, but only if nothing has been paid
--     against it yet (paid_amount = 0) — refuses otherwise, since silently
--     dropping a debt that already has settlement history would destroy
--     that payment record. cash->debt creates a fresh pending debt for the
--     new total. Note: unlike place_order_transaction, this does NOT replay
--     the cash-to-old-debt FIFO offset — that offset already happened (or
--     didn't) at the time the sale was originally placed.
create or replace function public.edit_sale_transaction(
  p_sale_id bigint,
  p_cube_type text,
  p_quantity integer,
  p_price_per_cube numeric,
  p_payment_type text,
  p_edited_by text
) returns jsonb as $$
declare
  v_old_cube_type text;
  v_old_quantity integer;
  v_old_payment_type text;
  v_customer_id bigint;
  v_sale_code text;

  v_type_a text;
  v_type_b text;
  v_item_a_id bigint;
  v_item_a_qty integer;
  v_item_b_id bigint;
  v_item_b_qty integer;

  v_old_item_id bigint;
  v_old_item_qty integer;
  v_new_item_id bigint;
  v_new_item_qty integer;

  v_old_item_final_qty integer;
  v_new_item_final_qty integer;

  v_inventory_price numeric(10, 2);
  v_final_price numeric(10, 2);
  v_new_total numeric(10, 2);
  v_now timestamp with time zone := timezone('utc'::text, now());

  v_debt_id bigint;
  v_debt_paid numeric(10, 2);
  v_new_remaining numeric(10, 2);
  v_new_status text;
begin
  if p_quantity is null or p_quantity <= 0 then raise exception 'Quantity must be a positive integer'; end if;
  if p_cube_type not in ('manufactured', 'resell') then raise exception 'Invalid cube type selected'; end if;
  if p_payment_type not in ('cash', 'debt') then raise exception 'Invalid payment type'; end if;

  -- 1. Lock and read the existing sale
  select cube_type, quantity, payment_type, customer_id, sale_code
    into v_old_cube_type, v_old_quantity, v_old_payment_type, v_customer_id, v_sale_code
  from public.sales
  where id = p_sale_id
  for update;

  if not found then raise exception 'Sale record not found'; end if;

  -- 2. Lock the affected inventory row(s) in a fixed order to avoid deadlocks
  --    against concurrent edits/orders touching the same two cube types.
  if v_old_cube_type = p_cube_type then
    select id, quantity into v_old_item_id, v_old_item_qty
    from public.inventory where type = v_old_cube_type for update;
    if not found then raise exception 'Inventory item for % not found', v_old_cube_type; end if;
    v_new_item_id := v_old_item_id;
    v_new_item_qty := v_old_item_qty;
  else
    if v_old_cube_type < p_cube_type then
      v_type_a := v_old_cube_type; v_type_b := p_cube_type;
    else
      v_type_a := p_cube_type; v_type_b := v_old_cube_type;
    end if;

    select id, quantity into v_item_a_id, v_item_a_qty
    from public.inventory where type = v_type_a for update;
    if not found then raise exception 'Inventory item for % not found', v_type_a; end if;

    select id, quantity into v_item_b_id, v_item_b_qty
    from public.inventory where type = v_type_b for update;
    if not found then raise exception 'Inventory item for % not found', v_type_b; end if;

    if v_type_a = v_old_cube_type then
      v_old_item_id := v_item_a_id; v_old_item_qty := v_item_a_qty;
      v_new_item_id := v_item_b_id; v_new_item_qty := v_item_b_qty;
    else
      v_old_item_id := v_item_b_id; v_old_item_qty := v_item_b_qty;
      v_new_item_id := v_item_a_id; v_new_item_qty := v_item_a_qty;
    end if;
  end if;

  -- 3. Restore the old quantity, then deduct the new quantity
  if v_old_item_id = v_new_item_id then
    v_old_item_final_qty := v_old_item_qty + v_old_quantity - p_quantity;
    if v_old_item_final_qty < 0 then
      raise exception 'Insufficient stock. Available: %', v_old_item_qty + v_old_quantity;
    end if;

    update public.inventory
    set quantity = v_old_item_final_qty, updated_at = v_now
    where id = v_old_item_id;

    insert into public.inventory_transactions (inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by)
    values (v_old_item_id, 'adjustment', v_old_item_final_qty - v_old_item_qty, v_old_item_qty, v_old_item_final_qty, v_sale_code || ' (edit)', p_edited_by);
  else
    v_old_item_final_qty := v_old_item_qty + v_old_quantity;
    v_new_item_final_qty := v_new_item_qty - p_quantity;
    if v_new_item_final_qty < 0 then
      raise exception 'Insufficient stock. Available: %', v_new_item_qty;
    end if;

    update public.inventory
    set quantity = v_old_item_final_qty, updated_at = v_now
    where id = v_old_item_id;

    update public.inventory
    set quantity = v_new_item_final_qty, updated_at = v_now
    where id = v_new_item_id;

    insert into public.inventory_transactions (inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by)
    values (v_old_item_id, 'adjustment', v_old_quantity, v_old_item_qty, v_old_item_final_qty, v_sale_code || ' (edit restore)', p_edited_by);

    insert into public.inventory_transactions (inventory_id, transaction_type, quantity_change, previous_quantity, new_quantity, reference_code, created_by)
    values (v_new_item_id, 'adjustment', -p_quantity, v_new_item_qty, v_new_item_final_qty, v_sale_code || ' (edit deduct)', p_edited_by);
  end if;

  -- 4. Resolve price the same way place_order_transaction does: admins may
  --    override, everyone else always gets the current inventory price.
  select price_per_cube into v_inventory_price from public.inventory where id = v_new_item_id;

  if public.is_admin() and p_price_per_cube is not null and p_price_per_cube > 0 then
    v_final_price := p_price_per_cube;
  else
    v_final_price := v_inventory_price;
  end if;

  if v_final_price is null or v_final_price <= 0 then
    raise exception 'Price per cube must be a valid positive number';
  end if;

  v_new_total := v_final_price * p_quantity;

  -- 5. Update the sale record
  update public.sales
  set cube_type = p_cube_type,
      quantity = p_quantity,
      price_per_cube = v_final_price,
      total_amount = v_new_total,
      payment_type = p_payment_type,
      bill_pdf_url = null
  where id = p_sale_id;

  -- 6. Reconcile the linked debt (if any) against the new payment terms/total
  select id, paid_amount into v_debt_id, v_debt_paid
  from public.debts
  where sale_id = p_sale_id
  for update;

  if v_old_payment_type = 'debt' and p_payment_type = 'debt' then
    -- Still a debt: re-price it, keeping whatever has already been paid.
    v_new_remaining := v_new_total - coalesce(v_debt_paid, 0);
    if v_new_remaining < 0 then
      raise exception 'New total (LKR %) is less than the LKR % already paid against this debt', v_new_total, v_debt_paid;
    end if;
    v_new_status := case when v_new_remaining <= 0 then 'settled' else (case when v_debt_paid > 0 then 'partial' else 'pending' end) end;

    update public.debts
    set total_amount = v_new_total,
        remaining_amount = v_new_remaining,
        status = v_new_status
    where id = v_debt_id;

  elsif v_old_payment_type = 'debt' and p_payment_type = 'cash' then
    -- Converting to cash: only safe to drop the debt if nothing has been
    -- collected against it yet.
    if v_debt_id is not null and coalesce(v_debt_paid, 0) > 0 then
      raise exception 'Cannot convert to cash: LKR % has already been settled against this sale''s debt', v_debt_paid;
    end if;
    delete from public.debts where id = v_debt_id;

  elsif v_old_payment_type = 'cash' and p_payment_type = 'debt' then
    -- Converting to debt: open a fresh pending debt for the new total.
    insert into public.debts (sale_id, customer_id, total_amount, paid_amount, remaining_amount, status, created_at)
    values (p_sale_id, v_customer_id, v_new_total, 0, v_new_total, 'pending', v_now)
    returning id into v_debt_id;
  end if;

  return jsonb_build_object(
    'id', p_sale_id,
    'sale_code', v_sale_code,
    'customer_id', v_customer_id,
    'cube_type', p_cube_type,
    'quantity', p_quantity,
    'price_per_cube', v_final_price,
    'total_amount', v_new_total,
    'payment_type', p_payment_type,
    'debt_id', v_debt_id
  );
end;
$$ language plpgsql security definer;

-- Atomic Inventory Update Price
create or replace function public.update_inventory_price(p_id bigint, p_price numeric)
returns void as $$
begin
  if not public.is_admin() then
    raise exception 'Only administrators can update inventory prices';
  end if;
  
  if p_price <= 0 then
    raise exception 'Price must be a positive value';
  end if;

  update public.inventory
  set price_per_cube = p_price,
      updated_at = timezone('utc'::text, now())
  where id = p_id;
end;
$$ language plpgsql security definer;

