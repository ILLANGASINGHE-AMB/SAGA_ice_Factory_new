-- ----------------------------------------------------------------------------
-- 11. Ledger consistency assertions
--
-- Standing in for the tests the audit asks for (this project has no test
-- runner). Each row this returns is a real inconsistency; a clean database
-- returns none, so it works as a CI gate:
--
--   select * from public.ledger_consistency_report();   -- expect 0 rows
--
-- Deliberately a report rather than a CHECK constraint / trigger: the
-- sale_items-vs-header invariant spans two tables, and a hard constraint added
-- now would also reject writes touching rows left inconsistent by the code
-- these fixes replace — turning a historical data problem into an outage.
-- ----------------------------------------------------------------------------

create or replace function public.ledger_consistency_report()
returns table (check_name text, entity_id text, detail text) as $$
  -- FIN-01: billed line items must add up to the sale header's quantity.
  select 'sale_items_vs_sales_quantity'::text,
         s.sale_code,
         format('header quantity %s, paid line items %s', s.quantity, coalesce(i.paid_qty, 0))
    from public.sales s
    left join (
      select sale_id, sum(quantity) filter (where not is_free) as paid_qty
        from public.sale_items group by sale_id
    ) i on i.sale_id = s.id
   where exists (select 1 from public.sale_items si where si.sale_id = s.id)
     and coalesce(i.paid_qty, 0) <> s.quantity

  union all

  -- FIN-09: free cubes physically left stock, so they must be recorded too.
  select 'sale_items_vs_sales_free_quantity'::text,
         s.sale_code,
         format('header free_quantity %s, free line items %s', s.free_quantity, coalesce(i.free_qty, 0))
    from public.sales s
    left join (
      select sale_id, sum(quantity) filter (where is_free) as free_qty
        from public.sale_items group by sale_id
    ) i on i.sale_id = s.id
   where exists (select 1 from public.sale_items si where si.sale_id = s.id)
     and coalesce(i.free_qty, 0) <> coalesce(s.free_quantity, 0)

  union all

  -- FIN-02: a debt's created_at is its incurrence date and must equal its
  -- sale's date. Anything else means something moved it again.
  select 'debt_created_at_vs_sale_date'::text,
         d.id::text,
         format('debt created_at %s, sale_date %s', d.created_at, s.sale_date)
    from public.debts d
    join public.sales s on s.id = d.sale_id
   where d.created_at is distinct from s.sale_date

  union all

  -- FIN-03 / FIN-04: paid_amount is the sum of a debt's settlements. A
  -- mismatch means a settlement was added or reversed without the debt.
  select 'debt_paid_amount_vs_settlements'::text,
         d.id::text,
         format('debt paid_amount %s, settlements %s', d.paid_amount, coalesce(x.total, 0))
    from public.debts d
    left join (
      select debt_id, sum(amount_paid) as total
        from public.debt_settlements group by debt_id
    ) x on x.debt_id = d.id
   where d.paid_amount is distinct from coalesce(x.total, 0)

  union all

  -- FIN-04: remaining_amount is always total minus paid.
  select 'debt_remaining_amount'::text,
         d.id::text,
         format('total %s - paid %s <> remaining %s', d.total_amount, d.paid_amount, d.remaining_amount)
    from public.debts d
   where d.remaining_amount is distinct from (d.total_amount - d.paid_amount)

  union all

  -- FIN-17: a cash order whose cash was diverted to the customer's older
  -- invoices must carry a debt of exactly what was diverted.
  --
  -- The cap at the order total matters: cash cannot fund more of other
  -- invoices than the customer actually handed over for this one, so an
  -- `applied` above the order total is itself the bug being caught.
  --
  -- A cash order that diverted nothing must carry no debt, which the same
  -- comparison covers -- least(0, total) is 0.
  select 'cash_order_shortfall_debt'::text,
         s.sale_code,
         format('cash order %s diverted %s to older invoices but carries a debt of %s (expected %s)',
                s.total_amount, coalesce(x.applied, 0), coalesce(d.total_amount, 0),
                least(coalesce(x.applied, 0), s.total_amount))
    from public.sales s
    left join (
      select source_sale_id, sum(amount_paid) as applied
        from public.debt_settlements
       where is_auto_applied and source_sale_id is not null
       group by source_sale_id
    ) x on x.source_sale_id = s.id
    left join public.debts d on d.sale_id = s.id
   where s.payment_type = 'cash'
     and coalesce(d.total_amount, 0)
         is distinct from least(coalesce(x.applied, 0), s.total_amount)

  union all

  -- FIN-17: the business rule itself. What a customer owes is the ice they
  -- took on credit, less every rupee they actually handed over. Cash orders
  -- appear on neither side -- they pay for themselves -- which is exactly why
  -- one can never move the balance.
  --
  -- Auto-applied settlements are excluded from "handed over" on purpose: that
  -- row is the FIFO offset moving a balance between two invoices, not new
  -- money at the till. Counting it would credit the same rupees twice, which
  -- is the original FIN-17 loss in a different guise.
  --
  -- Debts with no sale behind them (a hand-entered opening balance) count as
  -- credit taken, or every such customer reports as broken.
  select 'customer_outstanding_vs_ledger'::text,
         coalesce(c.customer_code, c.id::text),
         format('open debts %s, but credit taken %s - payments received %s = %s',
                t.owed, t.credit_taken, t.payments, t.credit_taken - t.payments)
    from public.customers c
    join lateral (
      select
        coalesce((select sum(d.remaining_amount)
                    from public.debts d
                   where d.customer_id = c.id and d.status <> 'settled'), 0) as owed,
        coalesce((select sum(s.total_amount)
                    from public.sales s
                   where s.customer_id = c.id and s.payment_type = 'debt'), 0)
        + coalesce((select sum(d.total_amount)
                      from public.debts d
                     where d.customer_id = c.id and d.sale_id is null), 0) as credit_taken,
        coalesce((select sum(ds.amount_paid)
                    from public.debt_settlements ds
                   where ds.customer_id = c.id and not ds.is_auto_applied), 0) as payments
    ) t on true
   where t.owed is distinct from (t.credit_taken - t.payments)

  union all

  -- FIN-04: a settlement taken as a cheque or a bank transfer never touches
  -- the till, so the ONLY thing holding that money is its cheque_records /
  -- bank_deposits row. The code this replaces wrote that row in a separate
  -- transaction that could fail into a toast, leaving the debt marked paid
  -- with the funds recorded in no store of value at all.
  select 'settlement_without_ledger_row'::text,
         coalesce(ds.settlement_code, ds.id::text),
         format('%s settlement of %s has no %s row',
                ds.payment_method, ds.amount_paid,
                case when ds.payment_method = 'cheque' then 'cheque_records' else 'bank_deposits' end)
    from public.debt_settlements ds
   where not ds.is_auto_applied
     and ds.payment_method in ('cheque', 'bank_transfer')
     -- Either kind of settlement produces exactly one ledger row, in one
     -- table or the other, so "neither table has it" is the whole test.
     and not exists (
       select 1 from public.cheque_records c where c.settlement_id = ds.id
       union all
       select 1 from public.bank_deposits b where b.settlement_id = ds.id
     )

  union all

  -- FIN-16: a deposited cheque must point at a bank deposit that still
  -- exists, or its amount is counted in neither store of value.
  select 'deposited_cheque_without_deposit'::text,
         c.cheque_no,
         format('cheque %s is marked deposited with deposit_id %s', c.cheque_no, c.deposit_id)
    from public.cheque_records c
   where c.status = 'deposited'
     and (c.deposit_id is null
          or not exists (select 1 from public.bank_deposits b where b.id = c.deposit_id));
$$ language sql stable security definer set search_path = public;

-- --------------------------------------------------------------------------
-- One customer's receivables, event by event
-- --------------------------------------------------------------------------
-- What the report above cannot do is show WHERE a balance went wrong. This
-- replays a single customer's orders and payments in the order they happened,
-- so the chain can be read off directly:
--
--   select * from public.customer_debt_ledger(<customer_id>);
--
--   kind          code   order_total  cash_diverted  debt_opened  balance_after
--   credit order  S0001       32,500              0       32,500         32,500
--   cash order    S0002       40,000         32,500       32,500         32,500
--   cash order    S0003       95,000         32,500       32,500         32,500
--
-- balance_after is derived from the business rule, NOT from the debts table:
-- credit taken so far minus payments received so far. Where it stops agreeing
-- with the debt rows on the same line is where the bug is. A cash order moves
-- it by zero, every time -- that column IS the invariant.
create or replace function public.customer_debt_ledger(p_customer_id bigint)
returns table (
  occurred_at    timestamptz,
  kind           text,
  code           text,
  order_total    numeric,
  cash_diverted  numeric,
  debt_opened    numeric,
  debt_remaining numeric,
  balance_after  numeric
) as $$
  -- Every output column below is qualified with the `e.` alias on purpose.
  -- In a SQL-language function the RETURNS TABLE names are parameters, and an
  -- unqualified `occurred_at` in the outer select is ambiguous against them --
  -- the kind of ambiguity that resolves to a column of NULLs rather than an
  -- error. Qualifying leaves nothing to resolve.
  with events as (
    select
      s.sale_date as ev_at,
      case when s.payment_type = 'debt' then 'credit order' else 'cash order' end as ev_kind,
      s.sale_code as ev_code,
      s.total_amount as ev_order_total,
      -- What this order's cash was pulled away to pay off elsewhere.
      coalesce((select sum(ds.amount_paid)
                  from public.debt_settlements ds
                 where ds.source_sale_id = s.id and ds.is_auto_applied), 0) as ev_diverted,
      coalesce((select d.total_amount from public.debts d
                 where d.sale_id = s.id order by d.id limit 1), 0) as ev_debt_opened,
      coalesce((select d.remaining_amount from public.debts d
                 where d.sale_id = s.id order by d.id limit 1), 0) as ev_debt_remaining,
      -- Only credit orders move the balance. This is the whole rule.
      case when s.payment_type = 'debt' then s.total_amount else 0 end as ev_delta,
      s.id as ev_tiebreak
    from public.sales s
    where s.customer_id = p_customer_id

    union all

    -- Real money handed over later. Auto-applied rows are deliberately absent:
    -- they are an internal transfer between two of this customer's invoices,
    -- already accounted for by the shortfall the funding order opened.
    select
      ds.settlement_date,
      'payment (' || ds.payment_method || ')',
      ds.settlement_code,
      0, 0, 0, 0,
      -ds.amount_paid,
      ds.id
    from public.debt_settlements ds
    where ds.customer_id = p_customer_id
      and not ds.is_auto_applied
  )
  select
    e.ev_at, e.ev_kind, e.ev_code, e.ev_order_total,
    e.ev_diverted, e.ev_debt_opened, e.ev_debt_remaining,
    sum(e.ev_delta) over (order by e.ev_at, e.ev_tiebreak
                          rows between unbounded preceding and current row)
  from events e
  order by e.ev_at, e.ev_tiebreak;
$$ language sql stable security definer set search_path = public;

grant execute on function public.ledger_consistency_report() to authenticated;
grant execute on function public.customer_debt_ledger(bigint) to authenticated;


-- ==========================================================================
-- Settings → Clear Database
-- ==========================================================================
-- Wipes every table in the `public` schema in one transaction, except the
-- three held back below. Login information is the only thing that survives:
-- `auth.users` and the `profiles` rows carrying each account's role, name and
-- username.
--
-- The wipe list is discovered from the live catalog rather than hardcoded --
-- see the comment inside the function for why a hand-maintained list is the
-- wrong shape for an operation whose whole promise is that nothing is left
-- behind.

create or replace function public.clear_all_data()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tables text;
begin
  if not public.is_admin() then
    raise exception 'Only admins can clear the database';
  end if;

  -- A DENYLIST, not an allowlist -- deliberately.
  --
  -- Naming the tables to wipe was the first attempt at this and it was the
  -- wrong shape twice over. It rots the moment a feature adds a table, and it
  -- rots SILENTLY: data survives the one operation whose entire promise is
  -- that nothing survives. It also goes stale in the other direction -- the
  -- first draft listed `drivers`, dropped back in
  -- 20260821080000_link_transport_to_employees.sql when drivers were folded
  -- into `employees`, so the whole function aborted on a table that had not
  -- existed for months.
  --
  -- Discovering the list from the live catalog fixes both: a table added next
  -- month is wiped automatically, and a table dropped last month cannot
  -- reappear here. Only three are held back, and only for structural reasons:
  --
  --   profiles  -- login information, the one thing that must survive.
  --   inventory -- the MFC/RSC/BNC/DGC catalog rows are looked up by `type`
  --                by the order-placement RPCs, which expect exactly one row
  --                per cube type. Deleting them would brick Sales rather than
  --                blank it, so it is reset in place below instead.
  --   settings  -- useSettings() expects a single row. Reset in place below.
  select string_agg(format('public.%I', c.relname), ', ')
    into v_tables
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public'
     and c.relkind = 'r'
     and not c.relispartition
     and c.relname not in ('profiles', 'inventory', 'settings')
     -- Anything an extension owns (pg_depend deptype 'e') is infrastructure,
     -- not factory data; truncating one could break the extension.
     and not exists (
       select 1 from pg_depend d
        where d.objid = c.oid and d.deptype = 'e'
     );

  if v_tables is not null then
    -- One TRUNCATE over the whole set at once, so FK order stops mattering --
    -- Postgres checks the set as a whole rather than statement by statement,
    -- which is what made the old children-before-parents ordering necessary.
    -- RESTART IDENTITY puts row ids back to 1 so the system genuinely reads
    -- as a fresh install rather than carrying on from the old data's numbers.
    -- CASCADE cannot reach the three held-back tables: it only pulls in
    -- tables that REFERENCE a truncated one, and none of the three do
    -- (profiles points at auth.users; inventory and settings point nowhere).
    execute format('truncate table %s restart identity cascade', v_tables);
  end if;

  -- Structural rows reset in place (see above). Both carry `where true`: this
  -- runs as the function owner, which has pg-safeupdate enabled and rejects
  -- an unqualified UPDATE.
  update public.inventory
     set quantity = 0,
         price_per_cube = null,
         updated_at = timezone('utc'::text, now())
   where true;

  update public.settings
     set company_name = 'Sagacious Ice Factory',
         company_address = '',
         company_phone = '',
         company_email = '',
         logo_url = null,
         favicon_url = null,
         gemini_api_key = '',
         ai_enabled = true,
         updated_at = timezone('utc'::text, now())
   where true;
end;
$$;

grant execute on function public.clear_all_data() to authenticated;

-- FIN-17 repair: rebuild receivables that pre-patch cash orders wrote off.
-- Dry run by default; see 20260826040000 for the full rationale.
create or replace function public.backfill_cash_order_shortfall_debts(
  p_dry_run boolean default true
)
returns table (
  sale_code       text,
  customer_name   text,
  sale_date       timestamptz,
  order_total     numeric,
  applied_to_old  numeric,
  shortfall       numeric,
  action          text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row record;
begin
  if not public.is_admin() then
    raise exception 'Only admins can repair receivables';
  end if;

  for v_row in
    select s.id, s.sale_code, s.sale_date, s.customer_id, s.total_amount,
           c.name as customer_name,
           sum(ds.amount_paid) as applied
      from public.sales s
      join public.debt_settlements ds
        on ds.source_sale_id = s.id and ds.is_auto_applied
      left join public.customers c on c.id = s.customer_id
     where s.payment_type = 'cash'
       -- Idempotency: a sale that already carries its own debt row has either
       -- been repaired already or was written by the patched RPC.
       and not exists (select 1 from public.debts d where d.sale_id = s.id)
     group by s.id, s.sale_code, s.sale_date, s.customer_id, s.total_amount, c.name
     order by s.sale_date, s.id
  loop
    -- The shortfall is whatever this order's cash was diverted to, capped at
    -- the order total: cash cannot fund more of other invoices than the
    -- customer actually handed over for this one.
    if not p_dry_run then
      insert into public.debts (
        sale_id, customer_id, total_amount, paid_amount, remaining_amount,
        status, created_at, last_activity_at
      ) values (
        v_row.id, v_row.customer_id,
        least(v_row.applied, v_row.total_amount), 0,
        least(v_row.applied, v_row.total_amount),
        'pending',
        -- Matches the sale's date, both for the `debt_created_at_vs_sale_date`
        -- ledger check and so FIFO aging places it correctly among the
        -- customer's other invoices.
        v_row.sale_date, timezone('utc'::text, now())
      );
    end if;

    sale_code      := v_row.sale_code;
    customer_name  := coalesce(v_row.customer_name, '(deleted customer)');
    sale_date      := v_row.sale_date;
    order_total    := v_row.total_amount;
    applied_to_old := v_row.applied;
    shortfall      := least(v_row.applied, v_row.total_amount);
    action         := case when p_dry_run then 'would create' else 'created' end;
    return next;
  end loop;
end;
$$;

grant execute on function public.backfill_cash_order_shortfall_debts(boolean) to authenticated;


-- ==========================================================================
-- Public debt-settlement receipt links (24-hour)
-- ==========================================================================
--
-- A sale's WhatsApp/SMS message already carries a /bill/<sale_code> link that
-- get_public_bill serves for 24 hours. A debt settlement's message carried no
-- link at all, so a customer who paid off a debt had no way to see or keep the
-- receipt — the settlement PDF only ever existed inside the app.
--
-- This is the settlement-side twin of get_public_bill, and follows exactly the
-- same rules:
--   * matched on the exact settlement_code,
--   * the 24-hour window is enforced HERE, server-side, so an expired link
--     stops returning receipt content rather than merely being told not to
--     render it,
--   * only the fields the receipt prints come back — no address, no other
--     debts, nothing about the customer's remaining ledger beyond the balance
--     the receipt itself states.
--
-- One customer payment is applied FIFO across several debts and writes one
-- debt_settlements row per debt, all sharing the same customer and the same
-- settlement_date (they are written inside one transaction from a single
-- `v_now`). The receipt is the whole payment, so the group is rebuilt from
-- that pair rather than returning only the row whose code was in the link.

create or replace function public.get_public_settlement_receipt(p_settlement_code text)
returns jsonb as $$
declare
  v_row public.debt_settlements%rowtype;
  v_customer public.customers%rowtype;
  v_settings public.settings%rowtype;
  v_age_hours numeric;
  v_ids bigint[];
  v_total numeric(12, 2);
  v_cheque_no text;
  v_bank_name text;
  v_lines jsonb;
begin
  if p_settlement_code is null or length(trim(p_settlement_code)) = 0 then
    return jsonb_build_object('status', 'not_found');
  end if;

  select * into v_row
  from public.debt_settlements
  where settlement_code = trim(p_settlement_code)
  limit 1;

  if not found then
    return jsonb_build_object('status', 'not_found');
  end if;

  v_age_hours := extract(epoch from (timezone('utc'::text, now()) - v_row.settlement_date)) / 3600.0;
  if v_age_hours >= 24 then
    -- Expired: acknowledge the receipt existed, return none of its content.
    return jsonb_build_object('status', 'expired', 'settlement_code', v_row.settlement_code);
  end if;

  -- Every row written by the same payment.
  select array_agg(id order by id), coalesce(sum(amount_paid), 0)
    into v_ids, v_total
  from public.debt_settlements
  where customer_id is not distinct from v_row.customer_id
    and settlement_date = v_row.settlement_date
    and is_auto_applied = v_row.is_auto_applied;

  select * into v_customer from public.customers where id = v_row.customer_id;
  select * into v_settings from public.settings order by id limit 1;

  -- Where the money went, when it wasn't cash. Both tables point at the FIRST
  -- settlement row of the payment (settle_customer_debt_transaction's
  -- v_first_id), so the lookup spans the whole group.
  select cr.cheque_no, cr.bank_name into v_cheque_no, v_bank_name
  from public.cheque_records cr
  where cr.settlement_id = any(v_ids)
  limit 1;

  if v_bank_name is null then
    select bd.bank_name into v_bank_name
    from public.bank_deposits bd
    where bd.settlement_id = any(v_ids)
    limit 1;
  end if;

  select coalesce(jsonb_agg(line order by line->>'settlement_code'), '[]'::jsonb)
    into v_lines
  from (
    select jsonb_build_object(
             'settlement_code', ds.settlement_code,
             -- Coalesced: a settlement whose debt row was removed (a deleted
             -- sale) would otherwise put nulls into the receipt's table, and
             -- the PDF's status pill has no text to size itself from.
             'sale_code', coalesce(s.sale_code, 'N/A'),
             'amount_applied', ds.amount_paid,
             'remaining_amount', coalesce(d.remaining_amount, 0),
             'status', coalesce(d.status, 'settled')
           ) as line
      from public.debt_settlements ds
      left join public.debts d on d.id = ds.debt_id
      left join public.sales s on s.id = d.sale_id
     where ds.id = any(v_ids)
  ) grouped;

  return jsonb_build_object(
    'status', 'ok',
    'settlement', jsonb_build_object(
      'settlement_code', v_row.settlement_code,
      'settlement_date', v_row.settlement_date,
      'payment_method', v_row.payment_method,
      'notes', v_row.notes,
      'created_by', v_row.created_by,
      'amount_paid', v_total,
      -- Defensive: generateSettlementReceiptPDF falls back to these scalars
      -- when the per-debt breakdown is empty (a settlement whose debt row has
      -- since been removed), and would otherwise read undefined.
      'remaining_amount', coalesce((
        select sum(remaining_amount) from public.debts
         where customer_id = v_row.customer_id and status <> 'settled'), 0),
      'status', 'settled',
      'cheque_no', v_cheque_no,
      'bank_name', v_bank_name,
      'customer', case
        when v_customer.id is null then null
        else jsonb_build_object(
          'name', v_customer.name,
          'customer_code', v_customer.customer_code,
          'whatsapp_number', v_customer.whatsapp_number
        )
      end,
      'settlements', v_lines,
      -- What the customer still owes in total after this payment. The receipt
      -- states it, so it is the one figure beyond this payment that is shared.
      'customer_remaining_total', coalesce((
        select sum(remaining_amount) from public.debts
         where customer_id = v_row.customer_id and status <> 'settled'), 0)
    ),
    'settings', jsonb_build_object(
      'company_name', coalesce(v_settings.company_name, 'Sagacious Ice Factory'),
      'company_address', coalesce(v_settings.company_address, ''),
      'company_phone', coalesce(v_settings.company_phone, ''),
      'company_email', coalesce(v_settings.company_email, ''),
      'logo_url', v_settings.logo_url
    )
  );
end;
$$ language plpgsql security definer set search_path = public;

-- Anonymous access is the entire point — this is the link a customer opens
-- from WhatsApp or SMS without logging in.
grant execute on function public.get_public_settlement_receipt(text) to anon, authenticated;


-- ==========================================================================
-- Public bill / receipt: the customer's standing balance
-- ==========================================================================
--
-- Every printed and on-screen document now states what the customer still
-- owes across ALL their invoices, and when that figure last moved — a bill's
-- own total, or a single settlement's remainder, is only part of the answer
-- for a customer carrying a balance.
--
-- The in-app documents read it from the loaded debts ledger (see
-- src/utils/customerDebt.js). The two anonymous pages cannot: every select
-- policy on `debts` is `to authenticated`, so the figures have to ship inside
-- the same security-definer payload the rest of the document already comes
-- from. Both functions are otherwise unchanged.
--
-- Only two scalars are added — a total and a timestamp. No debt rows, no other
-- invoices, nothing that widens what an expired-in-24-hours link exposes
-- beyond what the document itself prints.

create or replace function public.get_public_bill(p_sale_code text)
returns jsonb as $$
declare
  v_sale public.sales%rowtype;
  v_customer public.customers%rowtype;
  v_settings public.settings%rowtype;
  v_age_hours numeric;
  v_debt_total numeric(12, 2);
  v_debt_updated_at timestamptz;
begin
  if p_sale_code is null or length(trim(p_sale_code)) = 0 then
    return jsonb_build_object('status', 'not_found');
  end if;

  select * into v_sale
  from public.sales
  where sale_code = trim(p_sale_code)
  limit 1;

  if not found then
    return jsonb_build_object('status', 'not_found');
  end if;

  v_age_hours := extract(epoch from (timezone('utc'::text, now()) - v_sale.sale_date)) / 3600.0;
  if v_age_hours >= 24 then
    -- Expired: acknowledge the bill existed, but return none of its content.
    return jsonb_build_object('status', 'expired', 'sale_code', v_sale.sale_code);
  end if;

  select * into v_customer from public.customers where id = v_sale.customer_id;
  select * into v_settings from public.settings order by id limit 1;

  -- The balance counts open debts only; the timestamp is taken across all of
  -- them, settled included, so a customer who has just cleared everything gets
  -- "LKR 0.00, as of <when they cleared it>" rather than a blank.
  select coalesce(sum(remaining_amount) filter (where status <> 'settled'), 0),
         max(coalesce(last_activity_at, created_at))
    into v_debt_total, v_debt_updated_at
  from public.debts
  where customer_id = v_sale.customer_id;

  return jsonb_build_object(
    'status', 'ok',
    'sale', jsonb_build_object(
      'id', v_sale.id,
      'sale_code', v_sale.sale_code,
      'cube_type', v_sale.cube_type,
      'quantity', v_sale.quantity,
      'free_quantity', v_sale.free_quantity,
      'price_per_cube', v_sale.price_per_cube,
      'total_amount', v_sale.total_amount,
      'payment_type', v_sale.payment_type,
      -- FIN-17: a cash order can now carry a balance. When its cash was
      -- diverted to the customer's older invoices, the shortfall is booked as
      -- a debt against THIS sale — so a bill that simply says "Paid Cash"
      -- tells the customer they owe nothing while the ledger says otherwise.
      -- Both figures ship with the bill so it can state the truth.
      'outstanding', coalesce(
        (select d.remaining_amount from public.debts d where d.sale_id = v_sale.id), 0),
      'amount_paid', v_sale.total_amount - coalesce(
        (select d.remaining_amount from public.debts d where d.sale_id = v_sale.id), 0),
      -- What the customer owes in all, and when that last changed.
      'customer_debt_total', coalesce(v_debt_total, 0),
      'customer_debt_updated_at', v_debt_updated_at,
      'sale_date', v_sale.sale_date,
      'bill_pdf_url', v_sale.bill_pdf_url,
      'customer', case
        when v_customer.id is null then null
        else jsonb_build_object(
          'name', v_customer.name,
          'customer_code', v_customer.customer_code,
          'whatsapp_number', v_customer.whatsapp_number
        )
      end,
      'sale_items', coalesce(
        (select jsonb_agg(jsonb_build_object(
           'cube_type', si.cube_type,
           'quantity', si.quantity,
           'price_per_cube', si.price_per_cube,
           'subtotal', si.subtotal,
           'is_free', si.is_free
         ) order by si.id)
         from public.sale_items si
         where si.sale_id = v_sale.id),
        '[]'::jsonb
      )
    ),
    'settings', jsonb_build_object(
      'company_name', coalesce(v_settings.company_name, 'Sagacious Ice Factory'),
      'company_address', coalesce(v_settings.company_address, ''),
      'company_phone', coalesce(v_settings.company_phone, ''),
      'company_email', coalesce(v_settings.company_email, ''),
      'logo_url', v_settings.logo_url
    )
  );
end;
$$ language plpgsql security definer set search_path = public;

grant execute on function public.get_public_bill(text) to anon, authenticated;


