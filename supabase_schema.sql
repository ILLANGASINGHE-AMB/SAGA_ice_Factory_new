-- Profiles (linked to auth.users)
create table public.profiles (
  id uuid references auth.users on delete cascade primary key,
  role text not null check (role in ('admin', 'user')),
  full_name text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Inventory
create table public.inventory (
  id bigint generated by default as identity primary key,
  code text not null unique,
  type text not null check (type in ('manufactured', 'resell', 'waste')),
  quantity integer not null default 0,
  price_per_cube numeric(10, 2),
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Customers
create table public.customers (
  id bigint generated by default as identity primary key,
  customer_code text not null unique,
  name text not null,
  whatsapp_number text unique,
  contact_number text,
  address text default '',
  is_branch boolean not null default false,
  notes text default '',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint customers_has_a_number check (whatsapp_number is not null or contact_number is not null)
);

-- Sales
-- cube_type/price_per_cube are nullable: populated only when the whole
-- order reduces to exactly one (cube_type, price_per_cube) pair across all
-- its items (the common single-item case); null when an order mixes cube
-- types or per-row rates. quantity is always the sum across items. See
-- sale_items below for the per-order line items.
create table public.sales (
  id bigint generated by default as identity primary key,
  sale_code text not null unique,
  customer_id bigint references public.customers(id) on delete set null,
  cube_type text check (cube_type in ('manufactured', 'resell')),
  quantity integer not null,
  price_per_cube numeric(10, 2),
  total_amount numeric(10, 2) not null,
  payment_type text not null check (payment_type in ('cash', 'debt')),
  bill_pdf_url text,
  sale_date timestamp with time zone default timezone('utc'::text, now()) not null,
  created_by text not null
);

-- Sale Line Items — one order (one sale_code/one bill) can contain multiple
-- cube types, each its own row here.
create table public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  cube_type text not null check (cube_type in ('manufactured', 'resell')),
  quantity integer not null check (quantity > 0),
  price_per_cube numeric(10, 2) not null check (price_per_cube > 0),
  subtotal numeric(10, 2) not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_sale_items_sale_id on public.sale_items(sale_id);

-- Debts
create table public.debts (
  id bigint generated by default as identity primary key,
  sale_id bigint references public.sales(id) on delete cascade,
  customer_id bigint references public.customers(id) on delete cascade,
  total_amount numeric(10, 2) not null,
  paid_amount numeric(10, 2) not null default 0,
  remaining_amount numeric(10, 2) not null,
  status text not null check (status in ('pending', 'partial', 'settled')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Debt Settlements
create table public.debt_settlements (
  id bigint generated by default as identity primary key,
  debt_id bigint references public.debts(id) on delete cascade,
  customer_id bigint references public.customers(id) on delete cascade,
